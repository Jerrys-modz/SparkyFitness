#!/usr/bin/env node
// Builds src/components/exerciseStats/muscleFigurePaths.ts from the web's
// body-map SVG, so the phone draws the same figure the web tints.
//
// react-native-svg's SvgXml renders a whole document as one element, which
// cannot tell which muscle was tapped. The mobile figure draws one <Path> per
// region instead, and this is where those paths come from.
//
//   node scripts/generate-muscle-figure.mjs          write the module
//   node scripts/generate-muscle-figure.mjs --check  fail if it is stale
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const mobileRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..'
);
const SOURCE = path.resolve(
  mobileRoot,
  '../SparkyFitnessFrontend/public/images/muscle-male.svg'
);
const TARGET = path.resolve(
  mobileRoot,
  'src/components/exerciseStats/muscleFigurePaths.ts'
);

function attribute(tag, name) {
  const match = tag.match(new RegExp(`\\s${name}="([^"]*)"`));
  return match ? match[1] : null;
}

export function renderMuscleFigureModule(svg) {
  const viewBox = attribute(svg.match(/<svg[\s\S]*?>/)?.[0] ?? '', 'viewBox');
  if (!viewBox) throw new Error('muscle-male.svg has no viewBox');

  const paths = [];
  for (const [tag] of svg.matchAll(/<path[\s\S]*?\/>/g)) {
    const d = attribute(tag, 'd');
    if (!d) continue;
    paths.push({
      svgClass: attribute(tag, 'class'),
      // The two unclassed paths with a visible stroke are the body outlines
      // (front and back). Everything else is a filled region.
      outline: Number(attribute(tag, 'stroke-width') ?? '0') > 0,
      d: d.replace(/\s+/g, ' ').trim(),
    });
  }
  if (paths.length === 0) throw new Error('muscle-male.svg has no paths');

  const rows = paths.map((p) => `  ${JSON.stringify(p)},`).join('\n');
  return `/**
 * GENERATED by scripts/generate-muscle-figure.mjs from
 * SparkyFitnessFrontend/public/images/muscle-male.svg.
 * Do not edit by hand; run pnpm run muscle-figure:generate.
 */
export interface MuscleFigurePath {
  /** Region class from the SVG, mapped by svgClassToSchemaName. */
  svgClass: string | null;
  /** Body outline, drawn under the regions. */
  outline: boolean;
  d: string;
}

export const MUSCLE_FIGURE_VIEWBOX = ${JSON.stringify(viewBox)};

export const MUSCLE_FIGURE_PATHS: readonly MuscleFigurePath[] = [
${rows}
];
`;
}

function main() {
  const check = process.argv.includes('--check');
  const next = renderMuscleFigureModule(fs.readFileSync(SOURCE, 'utf8'));
  const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
  if (check) {
    if (current !== next) {
      console.error(
        `${path.relative(mobileRoot, TARGET)} is out of date with muscle-male.svg. Run pnpm run muscle-figure:generate.`
      );
      process.exit(1);
    }
    return;
  }
  if (current !== next) fs.writeFileSync(TARGET, next);
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
